/**
 * A descent rate is an average over TIME, and the corpus is what proves the difference matters.
 *
 * `legRate` used to average the instantaneous descent over sample INDEX. On an evenly-sampled log
 * that is the same number; on a log whose cadence changes during the descent it is not, and the
 * error is not random. A Featherweight GPS drops from 10 Hz to 0.5 Hz once the flight is under way,
 * so the crowded samples sit in the seconds after apogee where the rocket has barely started
 * falling, and the average comes out LOW — on the reading a flyer sizes a canopy against.
 *
 * This file is the case with real ground truth, and it is the strongest kind available: the log
 * carries the tracker's OWN vertical-speed column (`VERTV`, ft/s), which Debrief does not ingest —
 * it derives its speed from the altitude — so the column is an independent measurement of exactly
 * the quantity under test.
 */
describe('a descent rate is averaged over time, not over samples', () => {
  if (!present) {
    it.skip('corpus not fetched — run `npm run fetch-fixtures` (needs FIXTURES_TOKEN)', () => {});
    return;
  }
  const FILE = 'featherweight-gps/fwgps__trf-f1machbuster-jan10__GPSTrk05467_01-10-2026_14_55_35.csv';

  it("agrees with the tracker's own vertical-speed column over the same leg", () => {
    const loaded = loadForCompare(FILE);
    expect(loaded, 'the Featherweight GPS log is in the corpus').toBeTruthy();
    const { analysis } = loaded!;
    const apogee = analysis.events.find((e) => e.type === 'apogee');
    const main = analysis.events.find((e) => e.type === 'main');
    expect(apogee && main, 'the flight has both a drogue and a main leg').toBeTruthy();
    const rate = analysis.metrics.drogueDescentRate;
    expect(rate, 'a drogue rate is reported').not.toBeNull();

    // The file's own VERTV column, time-averaged over exactly the leg Debrief reports on. Read
    // from the raw bytes rather than from the parsed flight, because this column is deliberately
    // not part of the flight model — that is what makes it an independent check.
    const text = decodeBytes(new Uint8Array(readFileSync(CORPUS + FILE)));
    const lines = text.split(/\r?\n/);
    const head = lines.findIndex((l) => /(^|,)VERTV(,|$)/.test(l));
    expect(head, 'the log has a VERTV column').toBeGreaterThanOrEqual(0);
    const cols = lines[head].split(',').map((c) => c.trim());
    const [iT, iV] = [cols.indexOf('UNIXTIME'), cols.indexOf('VERTV')];
    const rows: [number, number][] = [];
    for (const line of lines.slice(head + 1)) {
      const c = line.split(',');
      if (c.length <= iV) continue;
      const t = Number(c[iT]);
      const v = Number(c[iV]);
      if (Number.isFinite(t) && Number.isFinite(v)) rows.push([t, v]);
    }
    expect(rows.length, 'the VERTV column has rows').toBeGreaterThan(100);

    // The analyzer's clock starts at the file's first sample, so the leg maps onto the raw rows by
    // elapsed time rather than by index.
    const t0 = rows[0][0];
    const from = apogee!.time;
    const to = main!.time;
    let sum = 0;
    let weight = 0;
    for (let i = 1; i < rows.length; i++) {
      const t = rows[i][0] - t0;
      if (t <= from || t > to) continue;
      const dt = rows[i][0] - rows[i - 1][0];
      if (!(dt > 0)) continue;
      sum += Math.abs(rows[i][1]) * 0.3048 * dt; // ft/s → m/s
      weight += dt;
    }
    const measured = sum / weight;

    // Measured 2026-07-31: Debrief 64.81 m/s, the tracker's own column 63.89 m/s — 1.4% apart, by
    // two different methods, over one leg. Averaged over SAMPLES instead, Debrief read 50.73 m/s,
    // which is 21% below the device. The band is 4%: wide enough that the two methods' honest
    // disagreement does not fail it, narrow enough that the defect could never have passed. It was
    // 8% for one commit and that was too slack — it would also have passed the version of this fix
    // that dropped each leg's closing interval, which reads 65.62 and is wrong for its own reason.
    expect(
      Math.abs(rate! - measured) / measured,
      `Debrief reads ${rate!.toFixed(2)} m/s where the tracker's own VERTV column averages ${measured.toFixed(2)} m/s over the same leg`,
    ).toBeLessThan(0.04);
  });

  it('does not rest the rate on the one sample the Hampel filter could not catch', () => {
    // The chord reads TWO samples out of a leg's however-many, and one of them is
    // `argMax(altClean)` — the record's most extreme sample BY CONSTRUCTION, which is exactly
    // where a positive spike survives. `legRate` answers that with a short median at each end,
    // and this record is why it has to.
    //
    // `blueraven meraki2-121km` peaks at 75,516 m on two samples sitting between neighbours of
    // 54,233 and 58,509. The Hampel filter cannot remove them: it needs a local consensus to
    // measure an outlier against, and at 121 km on a Blue Raven's inertial solution the whole
    // neighbourhood is that noisy. Read as a bare chord this leg published **138.85 m/s** off
    // those two samples. With the median endpoint it reads 107.4 — which is also, to 0.01%,
    // what the superseded smoothed estimator read here, and that agreement is the point: the
    // 2.4× corrections elsewhere in this change are real, and THIS record was never one of
    // them. Falsified by returning `alt[at]` from `legEndpoint`, which puts it back to 138.85.
    const file = 'blueraven/blueraven__reddit-meraki2-121km__BlueRaven-LR.csv';
    if (!existsSync(CORPUS + file)) return; // corpus not fetched — the sweep above says so
    const loaded = loadForCompare(file);
    expect(loaded, 'the 121 km Blue Raven analyses').not.toBeNull();
    const rate = loaded!.analysis.metrics.drogueDescentRate;
    expect(rate, 'a drogue rate is published for it').not.toBeNull();
    expect(rate!, 'the two spike samples must not set the rate').toBeLessThan(120);
    expect(rate!).toBeCloseTo(107.4, 0);
  });

  it('reports a rate that matches its own leg, across the whole corpus', { timeout: 120_000 }, async () => {
    // The general form of the same invariant: over a leg, the average descent rate IS the height
    // lost divided by the time taken. Where Debrief's figure and that chord disagree materially,
    // one of two things is true — the altitude trace over that leg is not sound (an anomaly, a
    // discontinuity), or the estimator is wrong. This is an EXACT count, so a new disagreement
    // fails and so does fixing one, which forces the number into the commit that earns it.
    //
    // ZERO, as of 2026-08-04. It was 8, and this comment used to say the cause was "only half
    // established: the 0.6 s moving average behind the descent series bleeds across the leg
    // boundaries". That was the right suspect and an understatement of it — there are THREE
    // index smoothers between the altitude and this figure (`altSmooth`, `baroVel`, `descent`),
    // and `timeMean` only telescopes to the chord when it is handed the bare finite difference.
    // Smoothing is exactly what destroys telescoping, and on a log whose cadence changes it
    // does so violently: a moving average is an INDEX window, so a fast sample beside a long
    // gap is smeared onto the samples bounding that gap, and `timeMean` then weights the
    // smeared value by the gap's whole duration.
    //
    // The leg rate is the chord now — measured on the recorded altitude rather than on
    // anything derived from it — so this count is 0 and the median error is 0.000%. Both
    // remaining doubts in the old comment are answered by that: the two drogue cases whose
    // altitude trace was called suspect were not suspect, and the split between legs reading
    // high and low was the index window, not the leg boundary.
    //
    // Keep this at 0. A non-zero count here is now a real regression rather than a known gap.
    const spec = JSON.parse(readFileSync(SPEC, 'utf8')) as { fixtures: Fixture[] };
    const off: string[] = [];
    const pcts: number[] = [];
    let legs = 0;
    let since = 0;
    /** Legs whose own device channel is not a usable witness, counted and reported rather
     *  than silently dropped — a skip that prints like a pass is the failure this whole file
     *  is built against. */
    let unusable = 0;
    let inertial = 0;
    // Two independent instruments reading one descent do not agree to the digit: the device
    // integrates its own sensor over its own window. 10% is far inside the defect this
    // replaced (2.4×) and outside the spread two honest reads produce — measured, the legs
    // that qualify agree to 1.7% at worst.
    const BAND = 10;
    for (const f of spec.fixtures) {
      if (++since >= 5) {
        since = 0;
        await breathe();
      }
      let loaded;
      try {
        loaded = loadForCompare(f.file);
      } catch {
        continue;
      }
      if (!loaded) continue;
      const { series, metrics, events } = loaded.analysis;
      const at = (t: string) => events.find((e) => e.type === t)?.index ?? null;
      const cases: [string, number | null, number | null, number | null][] = [
        ['drogue', at('apogee'), at('main'), metrics.drogueDescentRate],
        ['main', at('main'), at('landing'), metrics.mainDescentRate],
        ['whole', at('apogee'), at('landing'), metrics.wholeDescentRate],
      ];
      for (const [leg, a, b, reported] of cases) {
        if (a == null || b == null || reported == null || !(b > a + 1)) continue;
        const dt = series.time[b] - series.time[a];
        if (!(dt > 0)) continue;
        legs++;
        // AGAINST THE DEVICE'S OWN SPEED CHANNEL — a second instrument, not a second way of
        // reading the first one.
        //
        // This replaced a chord-versus-chord comparison, which is what the check degenerated
        // into the moment `legRate` itself became a chord: the sweep recomputed
        // `(altitude[a] - altitude[b]) / dt` at the same two indices, which is the same
        // arithmetic on the same doubles, and it agreed to 0.000% because it could not do
        // anything else. A test that cannot fail is worse than none — §9's own words, in a
        // file that had just spent a commit saying so about a different check. Caught by the
        // pre-push review, not by the suite. A second attempt measured the sensitivity of the
        // test's OWN reimplementation of the endpoint rule, which is the same mistake wearing
        // a different hat; the end-to-end version of that check lives in `analyze.test.ts`,
        // where it can perturb the input and watch the real pipeline respond.
        //
        // Only where the DEVICE measured speed. A baro-derived velocity is differentiated from
        // the same altitude the rate is read off, so agreeing with it establishes nothing.
        if (metrics.maxVelocitySource !== 'device' || !series.velocity) continue;
        let sw = 0;
        let sv = 0;
        for (let i = a + 1; i <= b; i++) {
          const w = series.time[i] - series.time[i - 1];
          const va = series.velocity[i - 1];
          const vb = series.velocity[i];
          if (!(w > 0) || !Number.isFinite(va) || !Number.isFinite(vb)) continue;
          sw += w;
          sv += ((Math.abs(va) + Math.abs(vb)) / 2) * w;
        }
        if (!(sw > 0)) continue;
        const own = sv / sw;
        // A device reading above free-fall-from-apogee is not a usable speed for this leg
        // either — the same first-principles ceiling the analyzer applies to its own figure.
        // On `blueraven meraki2-121km` the channel reads 3,976 m/s against a 1,217 m/s
        // ceiling, and on `trf-lemiv-l3` it reads 293 m/s under a main chute.
        const ceiling = Math.sqrt(2 * G0 * metrics.apogeeAltitude);
        if (!(own > 0) || own > ceiling) {
          unusable++;
          continue;
        }
        // A Blue Raven's altitude and velocity here are the board's INERTIAL estimates, and
        // `blueraven.ts` says so in the note it puts on every such flight: "The inertial
        // solution can drift after deployment." Deployment is where every one of these legs
        // begins, so that channel is not a witness on the descent — measured, it reads
        // 158 m/s over a drogue leg the altitude puts at 22 m/s. Excluded on the parser's own
        // statement rather than on the disagreement, which would be circular.
        if (loaded.analysis.warnings.some((w) => /inertial/i.test(w)) || f.file.includes('blueraven')) {
          inertial++;
          continue;
        }
        const pct = ((reported - own) / own) * 100;
        pcts.push(Math.abs(pct));
        if (Math.abs(pct) >= BAND) {
          off.push(`${f.file.split('/').pop()} ${leg}: Debrief ${reported.toFixed(2)} vs the device's own ${own.toFixed(2)} m/s (${pct.toFixed(1)}%)`);
        }
      }
    }
    expect(legs, 'the sweep actually examined descent legs').toBeGreaterThan(20);
    const abs = pcts.slice().sort((a, b) => a - b);
    const median = abs[Math.floor(abs.length / 2)];
    expect(
      off.length,
      `${legs} legs seen; ${pcts.length} checked against the device's own speed channel ` +
        `(${unusable} channel above free-fall, ${inertial} inertial-and-drifting), ` +
        `median |error| ${median.toFixed(3)}%, mean ${(abs.reduce((x, y) => x + y, 0) / abs.length).toFixed(3)}%\n` +
        `disagreeing by >=5%:\n${off.sort().join('\n')}`,
    ).toBe(0);
  });
});


/**
 * The published figure for what a DERIVED peak speed overstates by, recomputed from the corpus.
 *
 * D7 slice 2 asks for a headline reading to carry "a measured range whose basis is a corpus
 * statistic … and a test fails if the range is quoted without its basis". This is that test.
 *
 * It exists because the figures had drifted, and the way they drifted is the point: several sites
 * still published a **+30%** that was HONEST WHEN WRITTEN — the endurance StratoLogger against its
 * TeleMetrum — and stopped existing when the ascent-noise guard began withholding that peak (the
 * enumeration above this file's own pair list says so). Nothing connected the guard to the figure,
 * so the figure outlived the pair. `lib/derivedPeak.ts` holds them once now and this holds that
 * file to the corpus, so the published number shrinks with the enumeration instead of being
 * remembered.
 *
 * The basis is the corpus's own strongest ground truth — it is grouped by flight, so where one
 * recording MEASURED the speed and another differentiated it out of an altitude, the second is
 * bounded by the first. Nothing else in the corpus can bound a derived peak at all.
 */
describe('what a derived peak speed overstates by, measured rather than remembered', () => {
  if (!present) {
    it.skip('corpus not fetched', () => {});
    return;
  }
  it('matches lib/derivedPeak.ts, pair for pair', { timeout: 180_000 }, () => {
    const spec = JSON.parse(readFileSync(SPEC, 'utf8')) as { fixtures: { file: string; group?: string }[] };
    const groupOf = new Map(spec.fixtures.map((f) => [f.file, f.group]));
    const reads = corpusReads().filter((r) => r.reach === 'analysed' && r.metrics && !r.velocityWithheld);

    const byGroup = new Map<string, typeof reads>();
    for (const r of reads) {
      const g = groupOf.get(r.file);
      if (!g) continue;
      if (!byGroup.has(g)) byGroup.set(g, []);
      byGroup.get(g)!.push(r);
    }

    const pairs: { group: string; speedPct: number; machPct: number }[] = [];
    for (const [g, rs] of byGroup) {
      const measured = rs.filter((r) => r.metrics!.maxVelocitySource === 'device' && Number.isFinite(r.metrics!.maxVelocity));
      const derived = rs.filter((r) => r.metrics!.maxVelocitySource !== 'device' && Number.isFinite(r.metrics!.maxVelocity));
      if (!measured.length || !derived.length) continue;
      for (const d of derived) {
        // Against the CLOSEST measured read of that flight, so the figure is the smallest
        // defensible overstatement rather than the most dramatic one available.
        let best = measured[0];
        for (const m of measured) {
          if (Math.abs(m.metrics!.maxVelocity - d.metrics!.maxVelocity) < Math.abs(best.metrics!.maxVelocity - d.metrics!.maxVelocity)) best = m;
        }
        const speedPct = ((d.metrics!.maxVelocity - best.metrics!.maxVelocity) / best.metrics!.maxVelocity) * 100;
        const dm = d.metrics!.mach;
        const bm = best.metrics!.mach;
        const machPct = Number.isFinite(dm as number) && Number.isFinite(bm as number) && (bm as number) > 0
          ? (((dm as number) - (bm as number)) / (bm as number)) * 100
          : NaN;
        pairs.push({ group: g, speedPct, machPct });
      }
    }

    const shown = pairs
      .map((p) => `${p.group} +${p.speedPct.toFixed(1)}% speeds / +${p.machPct.toFixed(1)}% Mach`)
      .sort()
      .join('\n');

    // CONTAINMENT, not equality. A container's checked-out fixtures and the release asset
    // `corpus.lock.json` pins are not guaranteed to be the same corpus, and on 2026-08-01 they
    // were not: locally this found four pairs, CI found six. Equality would make the check pass on
    // exactly one corpus and go red on the other, which teaches the next session to widen it. So
    // every pair the corpus in front of us finds must be REPRESENTED in `lib/derivedPeak.ts` —
    // a pair the corpus shows and the published list omits is the failure that matters — while a
    // listed pair a smaller corpus cannot reproduce is not.
    for (const p of pairs) {
      const speed = Math.round(p.speedPct);
      const mach = Math.round(p.machPct);
      const match = DERIVED_PEAK_PAIRS.find((x) => x.speedPct === speed);
      expect(
        match,
        `the corpus shows a ${speed}% pair on ${p.group} that lib/derivedPeak.ts does not publish:\n${shown}`,
      ).toBeTruthy();
      expect(
        match!.machPct,
        `${p.group}: the Mach ratio must be computed, not copied from the speed ratio`,
      ).toBe(mach);
    }
    expect(DERIVED_PEAK_PAIRS.length, shown).toBeGreaterThanOrEqual(pairs.length);
    expect(DERIVED_PEAK_FLIGHTS, shown).toBeGreaterThanOrEqual(new Set(pairs.map((p) => p.group)).size);

    // The DIRECTION is the claim a flyer acts on, and it must not be more flattering than the
    // corpus. Publishing "always high" while any pair reads low would say a derived peak is an
    // upper bound when it is not — the exact overclaim this constant was set to `false` for.
    expect(
      DERIVED_PEAK_ALWAYS_HIGH,
      `some corpus pair reads LOW, so the published claim may not be "always high":\n${shown}`,
    ).toBe(pairs.every((p) => p.speedPct > 0) && DERIVED_PEAK_PAIRS.every((p) => p.speedPct > 0));

    // …and at least one pair must genuinely differ between the bases, or the distinction this
    // module exists to keep straight would be one nothing in the data supports.
    expect(
      pairs.some((p) => Math.round(p.speedPct) !== Math.round(p.machPct)),
      `the two bases must be different numbers on at least one real pair:\n${shown}`,
    ).toBe(true);
  });
});
